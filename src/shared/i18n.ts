const messages: Record<AppLocale, typeof zh> = { 'zh-CN': zh, 'en-US': en, 'ja-JP': ja };
export const copy = computed(() => messages[locale.value]);
export function formatBeanCount(count: number): string {
  if (locale.value === 'ja-JP') return `コーヒー豆${count}粒`;
  if (locale.value === 'zh-CN') return `${count} 颗咖啡豆`;
  return `${count} coffee ${count === 1 ? 'bean' : 'beans'}`;
}
export function duration(ms: number): string {
  const min = Math.floor(ms / 60000);
  return min >= 60
    ? `${Math.floor(min / 60)}${copy.value.hourShort} ${min % 60}${copy.value.minShort}`
    : `${min}${copy.value.minShort}`;
}
export function clock(ms: number): string {
  const sec = Math.ceil(Math.max(ms, 0) / 1000);
  return `${Math.floor(sec / 60)
    .toString()
    .padStart(2, '0')}:${(sec % 60).toString().padStart(2, '0')}`;
}
export function localDate(ms: number): string {
  return new Date(ms).toLocaleDateString(locale.value, { month: 'short', day: 'numeric' });
}
export function localTime(ms: number): string {
  return new Date(ms).toLocaleTimeString(locale.value, {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  });
}
